#!/usr/bin/env python3
"""
generate_feature_table.py - Render docs/supported-features.md from the data
tables in src/escpr_protocol.py, so the documentation can never drift from
the code.

The "tested" status is maintained by hand in TESTED below: only list things
that were actually printed on real hardware.

Usage:
    python3 scripts/generate_feature_table.py          # (re)write the file
    python3 scripts/generate_feature_table.py --check  # exit 1 if outdated

SPDX-License-Identifier: GPL-3.0-or-later
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import escpr_protocol as p  # noqa: E402

OUT = ROOT / "docs" / "supported-features.md"

# ---------------------------------------------------------------------------
# Hardware test log (edit by hand after every real test print)
# ---------------------------------------------------------------------------
TESTED = {
    "media": {"PlainPaper", "PhotoPaperGlossy"},
    "slots": {"Rear"},
    "sizes": {"A4"},
    "quality": {"High"},
    "color_modes": {"EpsonICC"},
}

# Features that are known to be missing (not just untested)
MISSING_NOTES = {
    "Roll": "feed path selected, but page length, cutting and cut lines are not implemented",
}

OK, UNTESTED, MISSING = "✅", "🟡", "❌"


def st(group: str, key: str) -> str:
    return OK if key in TESTED[group] else UNTESTED


def render() -> str:
    L: list[str] = []
    a = L.append
    a("<!-- GENERATED by scripts/generate_feature_table.py - do not edit by hand -->")
    a("")
    a("# Supported features")
    a("")
    a("> [!WARNING]")
    a("> This driver is **beta / experimental**. Only entries marked ✅ have been")
    a("> verified by printing on a real SC-P900. Everything else is implemented from")
    a("> Epson's driver data but has not been printed yet. Reports are welcome.")
    a("")
    a(f"Legend: {OK} tested on hardware · {UNTESTED} implemented, untested · {MISSING} not implemented")
    a("")
    a("## Printers")
    a("")
    a("| Model | Status |")
    a("|---|---|")
    a(f"| Epson SureColor SC-P900 | {OK} |")
    a(f"| Epson SureColor SC-P700 | {UNTESTED} same protocol and data family, never printed |")
    a("")
    a("## Media types")
    a("")
    a("Black ink (PK = Photo Black, MK = Matte Black) is chosen by the printer from the media type; "
      "the column shows the expected ink, which has only been confirmed where tested.")
    a("")
    a("| Status | CUPS `MediaType` | Name | Media ID | Black | ICC profile | Carbon Black |")
    a("|---|---|---|---:|:---:|---|:---:|")
    for m in p.MEDIA_SPECS:
        a(
            f"| {st('media', m.key)} | `{m.key}` | {m.name} | {m.sn_id} | "
            f"{'MK' if m.is_matte else 'PK'} | `{m.icc_profile}` | "
            f"{'yes' if m.supports_carbon_black else '–'} |"
        )
    a("")
    a("## Paper sources")
    a("")
    a("| Status | CUPS `InputSlot` | Name | Notes |")
    a("|---|---|---|---|")
    for key, (name, _m1, _m2) in p.INPUT_SLOTS.items():
        status = st("slots", key)
        note = MISSING_NOTES.get(key, "")
        if note:
            status = f"{UNTESTED}/{MISSING}"
        elif key in ("FrontPosterBoard", "FrontNoEjectRoller"):
            note = "3 mm left/right, 20 mm top/bottom margin (per Epson PPD)"
        elif key.startswith("Front"):
            note = "3 mm margin on all 4 sides (per Epson PPD)"
        a(f"| {status} | `{key}` | {name} | {note} |")
    a("")
    a("## Paper sizes")
    a("")
    a("| Status | CUPS `PageSize` | Name | SC-P900 only |")
    a("|---|---|---|:---:|")
    for s in p.PAPER_SIZES:
        a(f"| {st('sizes', s.key)} | `{s.key}` | {s.name} | {'yes' if s.sc_p900_only else ''} |")
    a("")
    a("## Print quality")
    a("")
    a("The firmware only accepts certain quality levels per media type; the driver maps the")
    a("requested level to the nearest allowed one (table from Epson's driver data).")
    a("")
    a("| Status | CUPS `PrintQuality` | Description |")
    a("|---|---|---|")
    for key, (name, _v) in p.QUALITY_MODES.items():
        a(f"| {st('quality', key)} | `{key}` | {name} |")
    a("")
    a("## Color management")
    a("")
    a("| Status | CUPS `EpsonColorMode` | Description |")
    a("|---|---|---|")
    modes = {
        "EpsonICC": "Convert on the host with the Epson ICC profile for the selected paper; printer color adjustment off",
        "NoColorAdjustment": "Send RGB unchanged, printer color adjustment off (for your own profiles / profiling targets)",
        "EpsonStandard": "Let the printer firmware apply its own sRGB conversion",
        "AdvancedBW": "Epson Advanced Black & White Photo mode",
    }
    for key, desc in modes.items():
        a(f"| {st('color_modes', key)} | `{key}` | {desc} |")
    a("")
    a("Source color spaces: the embedded ICC profile of the input image is honoured "
      f"(sRGB {OK}, Adobe RGB {OK}); images without a profile are treated as sRGB.")
    a("")
    a("Rendering intents (`EpsonRenderingIntent`): `RelativeBPC` (default, "
      f"{OK}), `RelativeNoBPC`, `Perceptual`, `Saturation`, `Absolute` ({UNTESTED}).")
    a("")
    a("## Other options")
    a("")
    a("| Status | Option | Notes |")
    a("|---|---|---|")
    a(f"| {OK} | LCD preview thumbnail & job metadata (`ESC t tsnd` + `REMOTE1 HD`) | 272-px baseline JPEG + TLV settings |")
    a(f"| {UNTESTED} | Black Enhance Overcoat (`EpsonOverCoat`) | on by default for glossy media |")
    a(f"| {UNTESTED} | Unidirectional printing (`Unidirectional`) | |")
    a(f"| {UNTESTED} | Custom media (`custom_media.json`, `ESC q setl`, `ESC m seti`, `PrintDuty`, `DryingTime`) | NVRAM slot ID + on-the-fly parameters |")
    a(f"| {UNTESTED}/{MISSING} | Borderless (`Borderless`) | flag is sent, but the image is not enlarged beyond the edge like Epson's \"Auto Expand\" |")
    a(f"| {MISSING} | Duplex, CD/DVD layout helpers | |")
    a("")
    return "\n".join(L)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            sys.stderr.write(f"{OUT} is out of date; run scripts/generate_feature_table.py\n")
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
